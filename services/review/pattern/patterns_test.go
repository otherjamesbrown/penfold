func TestPatternValidate(t *testing.T) {
	tests := []struct {
		name      string
		pattern   *Pattern
		expectErr bool
	}{
		{
			name: "valid pattern",
			pattern: &Pattern{
				ID:       "pattern-1",
				TenantID: "tenant-1",
				Name:     "Test Pattern",
				Type:     PatternSender,
				Conditions: []PatternCondition{
					NewPatternCondition("sender", OpEquals, "test@example.com"),
				},
			},
			expectErr: false,
		},
		{
			name: "missing ID",
			pattern: &Pattern{
				TenantID: "tenant-1",
				Name:     "Test Pattern",
				Type:     PatternSender,
				Conditions: []PatternCondition{
					NewPatternCondition("sender", OpEquals, "test@example.com"),
				},
			},
			expectErr: true,
		},
		{
			name: "missing tenant ID",
			pattern: &Pattern{
				ID:   "pattern-1",
				Name: "Test Pattern",
				Type: PatternSender,
				Conditions: []PatternCondition{
					NewPatternCondition("sender", OpEquals, "test@example.com"),
				},
			},
			expectErr: true,
		},
		{
			name: "missing name",
			pattern: &Pattern{
				ID:       "pattern-1",
				TenantID: "tenant-1",
				Type:     PatternSender,
				Conditions: []PatternCondition{
					NewPatternCondition("sender", OpEquals, "test@example.com"),
				},
			},
			expectErr: true,
		},
		{
			name: "invalid type",
			pattern: &Pattern{
				ID:       "pattern-1",
				TenantID: "tenant-1",
				Name:     "Test Pattern",
				Type:     PatternType("invalid"),
				Conditions: []PatternCondition{
					NewPatternCondition("sender", OpEquals, "test@example.com"),
				},
			},
			expectErr: true,
		},
		{
			name: "no conditions",
			pattern: &Pattern{
				ID:         "pattern-1",
				TenantID:   "tenant-1",
				Name:       "Test Pattern",
				Type:       PatternSender,
				Conditions: []PatternCondition{},
			},
			expectErr: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := tt.pattern.Validate()
			if (err != nil) != tt.expectErr {
				t.Errorf("expected error: %v, got: %v", tt.expectErr, err)
			}
		})
	}
}

func TestPatternClone(t *testing.T) {
	original := NewPattern("tenant-1", "Original", PatternSender, []PatternCondition{
		NewPatternCondition("sender", OpEquals, "test@example.com"),
	})
	original.Description = "Test description"
	original.Tags = []string{"tag1", "tag2"}
	original.Metadata["key"] = "value"

	clone := original.Clone()

	// Verify basic fields
	if clone.ID != original.ID {
		t.Error("clone ID should match original")
	}
	if clone.Name != original.Name {
		t.Error("clone name should match original")
	}

	// Verify independence
	clone.Name = "Modified"
	if original.Name == clone.Name {
		t.Error("modifying clone should not affect original")
	}

	clone.Tags[0] = "modified"
	if original.Tags[0] == "modified" {
		t.Error("modifying clone tags should not affect original")
	}

	clone.Metadata["key"] = "modified"
	if original.Metadata["key"] == "modified" {
		t.Error("modifying clone metadata should not affect original")
	}
}

