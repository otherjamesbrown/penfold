func TestPatternUpdateStats(t *testing.T) {
	pattern := NewPattern("tenant-1", "Test", PatternSender, []PatternCondition{
		NewPatternCondition("sender", OpEquals, "test@example.com"),
	})

	// Record some matches
	pattern.UpdateStats(true, false, 10)
	pattern.UpdateStats(true, false, 20)
	pattern.UpdateStats(true, true, 15)

	if pattern.Stats.TotalMatches != 3 {
		t.Errorf("expected 3 total matches, got %d", pattern.Stats.TotalMatches)
	}
	if pattern.Stats.SuccessfulActions != 2 {
		t.Errorf("expected 2 successful actions, got %d", pattern.Stats.SuccessfulActions)
	}
	if pattern.Stats.OverriddenActions != 1 {
		t.Errorf("expected 1 overridden action, got %d", pattern.Stats.OverriddenActions)
	}
	if pattern.Stats.LastMatchedAt == nil {
		t.Error("expected last matched at to be set")
	}

	// Check average processing time
	expectedAvg := (10.0 + 20.0 + 15.0) / 3.0
	if pattern.Stats.AverageProcessingTimeMs != expectedAvg {
		t.Errorf("expected avg processing time %f, got %f", expectedAvg, pattern.Stats.AverageProcessingTimeMs)
	}
}

func TestPatternCalculateConfidence(t *testing.T) {
	pattern := NewPattern("tenant-1", "Test", PatternSender, []PatternCondition{
		NewPatternCondition("sender", OpEquals, "test@example.com"),
	})

	// No matches - should be 0
	conf := pattern.CalculateConfidence()
	if conf != 0.0 {
		t.Errorf("expected 0 confidence with no matches, got %f", conf)
	}

	// Add successful actions
	for i := 0; i < 10; i++ {
		pattern.UpdateStats(true, false, 10)
	}

	conf = pattern.CalculateConfidence()
	if conf <= 0.0 || conf > 1.0 {
		t.Errorf("confidence should be between 0 and 1, got %f", conf)
	}
}

func TestPatternJSON(t *testing.T) {
	original := NewPattern("tenant-1", "Test Pattern", PatternSender, []PatternCondition{
		NewPatternCondition("sender", OpEquals, "test@example.com"),
	})
	original.Description = "Test description"
	original.Confidence = 0.85
	original.Tags = []string{"tag1", "tag2"}

	// Serialize
	data, err := original.ToJSON()
	if err != nil {
		t.Fatalf("failed to serialize pattern: %v", err)
	}

	// Deserialize
	restored, err := PatternFromJSON(data)
	if err != nil {
		t.Fatalf("failed to deserialize pattern: %v", err)
	}

	// Verify
	if restored.ID != original.ID {
		t.Errorf("ID mismatch: expected %s, got %s", original.ID, restored.ID)
	}
	if restored.Name != original.Name {
		t.Errorf("Name mismatch: expected %s, got %s", original.Name, restored.Name)
	}
	if restored.Confidence != original.Confidence {
		t.Errorf("Confidence mismatch: expected %f, got %f", original.Confidence, restored.Confidence)
	}
	if len(restored.Tags) != len(original.Tags) {
		t.Errorf("Tags length mismatch: expected %d, got %d", len(original.Tags), len(restored.Tags))
	}
}

