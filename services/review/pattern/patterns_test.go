func TestPatternSet(t *testing.T) {
	ps := NewPatternSet("tenant-1")

	if ps.TenantID != "tenant-1" {
		t.Errorf("expected tenant ID 'tenant-1', got '%s'", ps.TenantID)
	}
	if !ps.Enabled {
		t.Error("expected pattern set to be enabled")
	}
	if len(ps.Patterns) != 0 {
		t.Errorf("expected 0 patterns, got %d", len(ps.Patterns))
	}

	// Add patterns
	p1 := NewPattern("tenant-1", "Pattern 1", PatternSender, []PatternCondition{
		NewPatternCondition("sender", OpEquals, "test@example.com"),
	})
	p1.Priority = 10

	p2 := NewPattern("tenant-1", "Pattern 2", PatternTopic, []PatternCondition{
		NewPatternCondition("category", OpEquals, "marketing"),
	})
	p2.Priority = 20

	ps.AddPattern(p1)
	ps.AddPattern(p2)

	if len(ps.Patterns) != 2 {
		t.Errorf("expected 2 patterns, got %d", len(ps.Patterns))
	}

	// Verify sorted by priority (highest first)
	if ps.Patterns[0].Priority != 20 {
		t.Error("patterns should be sorted by priority (highest first)")
	}

	// Get pattern by ID
	found := ps.GetPattern(p1.ID)
	if found == nil {
		t.Error("expected to find pattern by ID")
	}
	if found.Name != "Pattern 1" {
		t.Errorf("expected name 'Pattern 1', got '%s'", found.Name)
	}

	// Remove pattern
	removed := ps.RemovePattern(p1.ID)
	if !removed {
		t.Error("expected remove to return true")
	}
	if len(ps.Patterns) != 1 {
		t.Errorf("expected 1 pattern after removal, got %d", len(ps.Patterns))
	}

	// Try to remove non-existent
	removed = ps.RemovePattern("non-existent")
	if removed {
		t.Error("expected remove to return false for non-existent pattern")
	}
}

