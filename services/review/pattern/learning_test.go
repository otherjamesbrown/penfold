func TestPatternLearnerSuggestPatternsForTenant(t *testing.T) {
	detector := newTestDetector()
	config := &LearnerConfig{
		MinSupportCount:      2,
		MinConfidence:        0.7,
		MaxSuggestions:       10,
		LookbackDays:         30,
		EnableSenderPatterns: true,
		EnableTopicPatterns:  true,
	}
	learner := NewPatternLearner(config, detector)

	// Record decisions with clear pattern
	for i := 0; i < 5; i++ {
		item := &automation.ReviewItem{
			ID:       "item-" + string(rune('a'+i)),
			TenantID: "tenant-1",
			Sender:   "spam@example.com",
			Category: "spam",
		}
		decision := automation.NewDecision("tenant-1", "user-1", item, automation.ActionReject)
		learner.RecordDecision(decision)
	}

	ctx := context.Background()
	suggestions, err := learner.SuggestPatternsForTenant(ctx, "tenant-1")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	// Should have at least one suggestion
	if len(suggestions) == 0 {
		t.Log("no suggestions returned, may need more diverse data")
		return
	}

	// Verify suggestions have required fields
	for _, s := range suggestions {
		if s.ID == "" {
			t.Error("suggestion ID should be set")
		}
		if s.TenantID != "tenant-1" {
			t.Errorf("expected tenant ID 'tenant-1', got '%s'", s.TenantID)
		}
		if s.Pattern == nil {
			t.Error("suggestion should have a pattern")
		}
		if s.Status != "pending" {
			t.Errorf("expected status 'pending', got '%s'", s.Status)
		}
	}
}

