func TestPatternLearnerExtractPattern(t *testing.T) {
	detector := newTestDetector()
	config := DefaultLearnerConfig()
	config.MinSupportCount = 3
	config.MinConfidence = 0.8
	learner := NewPatternLearner(config, detector)

	// Create decisions with clear pattern
	decisions := make([]*automation.Decision, 0)
	for i := 0; i < 5; i++ {
		item := &automation.ReviewItem{
			ID:       "item-" + string(rune('a'+i)),
			TenantID: "tenant-1",
			Sender:   "newsletter@company.com",
			Category: "marketing",
		}
		decision := automation.NewDecision("tenant-1", "user-1", item, automation.ActionReject)
		decisions = append(decisions, decision)
	}

	pattern := learner.ExtractPattern(decisions)

	if pattern == nil {
		t.Skip("pattern extraction may need more specific data")
		return
	}

	if pattern.SuggestedAction != string(automation.ActionReject) {
		t.Errorf("expected suggested action 'reject', got '%s'", pattern.SuggestedAction)
	}
	if !pattern.AutoGenerated {
		t.Error("expected pattern to be auto-generated")
	}
	if pattern.Source != "learned" {
		t.Errorf("expected source 'learned', got '%s'", pattern.Source)
	}
}

