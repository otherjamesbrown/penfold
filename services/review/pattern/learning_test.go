func TestDeterminePatternType(t *testing.T) {
	tests := []struct {
		name       string
		conditions []PatternCondition
		expected   PatternType
	}{
		{
			name: "sender field",
			conditions: []PatternCondition{
				NewPatternCondition("sender", OpEquals, "test@example.com"),
			},
			expected: PatternSender,
		},
		{
			name: "category field",
			conditions: []PatternCondition{
				NewPatternCondition("category", OpEquals, "work"),
			},
			expected: PatternTopic,
		},
		{
			name: "hour_of_day field",
			conditions: []PatternCondition{
				NewPatternCondition("hour_of_day", OpEquals, 9),
			},
			expected: PatternTime,
		},
		{
			name: "source field",
			conditions: []PatternCondition{
				NewPatternCondition("source", OpEquals, "email"),
			},
			expected: PatternSource,
		},
		{
			name: "priority field",
			conditions: []PatternCondition{
				NewPatternCondition("priority", OpGreaterThan, 2),
			},
			expected: PatternPriority,
		},
		{
			name: "multiple conditions",
			conditions: []PatternCondition{
				NewPatternCondition("sender", OpEquals, "test@example.com"),
				NewPatternCondition("category", OpEquals, "work"),
			},
			expected: PatternSender, // First condition determines type
		},
		{
			name:       "empty conditions",
			conditions: []PatternCondition{},
			expected:   PatternContent,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := determinePatternType(tt.conditions)
			if result != tt.expected {
				t.Errorf("expected %s, got %s", tt.expected, result)
			}
		})
	}
}

