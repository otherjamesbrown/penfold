func TestFeedbackLoopGetAccuracy(t *testing.T) {
	fb := NewFeedbackLoop()

	// No feedback - default to 1.0
	accuracy := fb.GetAccuracy("pattern-1")
	if accuracy != 1.0 {
		t.Errorf("expected 1.0 accuracy with no feedback, got %f", accuracy)
	}

	// Add feedback
	fb.RecordFeedback("pattern-1", true)
	fb.RecordFeedback("pattern-1", true)
	fb.RecordFeedback("pattern-1", false)

	accuracy = fb.GetAccuracy("pattern-1")
	expectedAccuracy := 2.0 / 3.0
	if accuracy < expectedAccuracy-0.01 || accuracy > expectedAccuracy+0.01 {
		t.Errorf("expected accuracy ~%.2f, got %.2f", expectedAccuracy, accuracy)
	}
}

func TestFeedbackLoopGetOverrideRate(t *testing.T) {
	fb := NewFeedbackLoop()

	// No data
	rate := fb.GetOverrideRate("pattern-1")
	if rate != 0.0 {
		t.Errorf("expected 0 override rate with no data, got %f", rate)
	}

	// Add feedback and overrides
	fb.RecordFeedback("pattern-1", true)
	fb.RecordFeedback("pattern-1", true)
	fb.RecordOverride("pattern-1")
	fb.RecordOverride("pattern-1")

	rate = fb.GetOverrideRate("pattern-1")
	// 2 overrides out of 2 positive + 2 overrides = 4 total
	expectedRate := 2.0 / 4.0
	if rate < expectedRate-0.01 || rate > expectedRate+0.01 {
		t.Errorf("expected override rate ~%.2f, got %.2f", expectedRate, rate)
	}
}

func TestFeedbackLoopShouldDisable(t *testing.T) {
	fb := NewFeedbackLoop()

	// Record mostly negative feedback
	for i := 0; i < 10; i++ {
		positive := i < 2 // 2 positive, 8 negative
		fb.RecordFeedback("pattern-1", positive)
	}

	// Should disable (80% negative > 50% threshold)
	if !fb.ShouldDisable("pattern-1", 5, 0.7) {
		t.Error("expected to suggest disabling pattern with high negative ratio")
	}

	// Test override rate threshold with a pattern that has good accuracy
	// Record mostly positive feedback for pattern-2
	for i := 0; i < 10; i++ {
		positive := i < 8 // 8 positive, 2 negative (80% accuracy)
		fb.RecordFeedback("pattern-2", positive)
	}
	// pattern-2 has no overrides so override rate is 0, should not disable
	if fb.ShouldDisable("pattern-2", 5, 0.1) {
		t.Error("expected not to suggest disabling pattern with high accuracy and low override rate")
	}

	// Should not disable with insufficient feedback
	if fb.ShouldDisable("pattern-1", 20, 0.5) {
		t.Error("expected not to suggest disabling with insufficient feedback")
	}
}

